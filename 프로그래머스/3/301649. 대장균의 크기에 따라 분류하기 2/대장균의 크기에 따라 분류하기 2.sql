SELECT ID, 
    CASE
    WHEN RNK / TOTAL <= 0.25 THEN 'CRITICAL'
    WHEN RNK / TOTAL <= 0.5 THEN 'HIGH'
    WHEN RNK / TOTAL <=0.75 THEN 'MEDIUM'
    ELSE 'LOW'
    END AS COLONY_NAME
FROM (
    SELECT A.ID,
    (SELECT COUNT(*) FROM ECOLI_DATA B
    WHERE B.SIZE_OF_COLONY > A.SIZE_OF_COLONY) + 1 AS RNK
    , (SELECT COUNT(*) FROM ECOLI_DATA) AS TOTAL
    FROM ECOLI_DATA A
) AS T
ORDER BY ID 