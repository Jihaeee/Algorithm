SELECT COUNT(*) AS FISH_COUNT, MAX_LENGTH, F1.FISH_TYPE 
FROM (SELECT MAX(LENGTH) AS MAX_LENGTH, FISH_TYPE
      FROM FISH_INFO
      GROUP BY FISH_TYPE
      ) AS F1
JOIN FISH_INFO F2 ON F1.FISH_TYPE= F2.FISH_TYPE
GROUP BY F2.FISH_TYPE
HAVING AVG(IFNULL(F2.LENGTH,10)) >= 33
ORDER BY F1.FISH_TYPE