SELECT A.AUTHOR_ID, A.AUTHOR_NAME, CATEGORY, SUM(B.PRICE * BS.SALES) AS TOTAL_SALES
FROM BOOK B, AUTHOR A,
    (SELECT SUM(SALES) AS SALES, BOOK_ID
     FROM BOOK_SALES
     WHERE YEAR(SALES_DATE) = 2022 AND MONTH(SALES_DATE) = 1
    GROUP BY BOOK_ID) AS BS
WHERE B.AUTHOR_ID = A.AUTHOR_ID AND BS.BOOK_ID = B.BOOK_ID
GROUP BY A.AUTHOR_NAME, B.CATEGORY
ORDER BY AUTHOR_ID, CATEGORY DESC