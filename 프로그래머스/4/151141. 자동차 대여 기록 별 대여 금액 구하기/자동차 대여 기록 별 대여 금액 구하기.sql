SELECT H.HISTORY_ID, ((C.DAILY_FEE * H.DURATION)* (1- IFNULL(DISCOUNT_RATE/100,0))) AS FEE
FROM CAR_RENTAL_COMPANY_CAR C
JOIN
    (SELECT HISTORY_ID, CAR_ID, DATEDIFF(END_DATE, START_DATE) +1 AS DURATION,
      CASE
        WHEN DATEDIFF(END_DATE, START_DATE) +1 >= 90 THEN '90일 이상'
        WHEN DATEDIFF(END_DATE, START_DATE) +1 >= 30 THEN '30일 이상'
        WHEN DATEDIFF(END_DATE, START_DATE) +1 >= 7 THEN '7일 이상'
        ELSE NULL
      END AS DURATION_TYPE 
     FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
     ) AS H ON C.CAR_ID = H.CAR_ID
LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN D ON D.CAR_TYPE = C.CAR_TYPE AND H.DURATION_TYPE = D.DURATION_TYPE
WHERE C.CAR_TYPE = '트럭' 
ORDER BY FEE DESC, HISTORY_ID DESC