SELECT YEAR, MONTH, GENDER, COUNT(*) AS USERS
FROM USER_INFO U,
     (SELECT YEAR(SALES_DATE) AS YEAR, MONTH(SALES_DATE) AS MONTH, USER_ID
     FROM ONLINE_SALE
     GROUP BY YEAR(SALES_DATE), MONTH(SALES_DATE), USER_ID) AS O
WHERE U.USER_ID = O.USER_ID AND GENDER IS NOT NULL
GROUP BY YEAR, MONTH, GENDER
ORDER BY YEAR, MONTH, GENDER
