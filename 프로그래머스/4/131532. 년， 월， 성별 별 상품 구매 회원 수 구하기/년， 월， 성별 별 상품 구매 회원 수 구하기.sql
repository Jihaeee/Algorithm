SELECT YEAR, MONTH, GENDER, COUNT(*) AS USERS
FROM (SELECT YEAR(SALES_DATE) AS YEAR, MONTH(SALES_DATE) AS MONTH, GENDER, U.USER_ID
      FROM USER_INFO U, ONLINE_SALE O
      WHERE U.USER_ID = O.USER_ID AND GENDER IS NOT NULL
      GROUP BY YEAR(SALES_DATE), MONTH(SALES_DATE), GENDER, U.USER_ID) AS T
GROUP BY YEAR, MONTH, GENDER
ORDER BY YEAR, MONTH, GENDER 